/* Package existing question images for lazy use from a file:// webpage. */
'use strict';
const fs=require('node:fs'),path=require('node:path');
const C=require('../dist/platform-core.js');
const ROOT=path.resolve(__dirname,'..'),DIST=path.join(ROOT,'dist');
const OUTPUT=path.join(DIST,'question-image-data'),LOADER=path.join(DIST,'question-images-ai.js');
const IMAGE_LIMIT=1800000,OUTPUT_LIMIT=80*1024*1024,CHUNK_SIZE=16;
const absent=value=>!String(value??'').trim()||/^(?:未附|未知|暂无|未提供|无解析|无答案|待补充|N\/?A|none|null|原资料未(?:提供|附).*)[。.]?$/i.test(String(value).trim());
const within=(file,directory)=>{const relative=path.relative(directory,file);return relative!==''&&!relative.startsWith('..'+path.sep)&&relative!=='..'&&!path.isAbsolute(relative);};
function eligibleAssets(bank){
  const materials=new Map(bank.materials.map(material=>[material.id,material])),assets=new Set();
  for(const question of bank.questions){
    if(question.category==='AWA')continue;
    const answer=(Array.isArray(question.correct_answer)?question.correct_answer:[]).map(String).filter(value=>!absent(value));
    if(!answer.length&&!absent(question.answer_text||question.raw_answer))answer.push(String(question.answer_text||question.raw_answer));
    const missingAnswer=!answer.length,missingExplanation=absent(question.explanation)&&!question.explanation_images?.length;
    if(!missingAnswer&&!missingExplanation)continue;
    for(const image of [...(materials.get(question.material_id)?.images||[]),...(question.images||[]),...(!missingAnswer?[]:question.explanation_images||[])])if(C.localAsset(image?.src))assets.add(image.src);
  }
  return [...assets].sort();
}
function imageData(src){
  if(!C.localAsset(src))return null;
  const extension=path.extname(src).toLowerCase(),type={'.png':'png','.jpg':'jpeg','.jpeg':'jpeg','.webp':'webp'}[extension];
  if(!type)return null;
  const directory=path.join(DIST,src.split('/')[0]),target=path.resolve(DIST,src);
  if(!within(target,directory))return null;
  let real,realDirectory,realDist,stat;
  try{real=fs.realpathSync(target);realDirectory=fs.realpathSync(directory);realDist=fs.realpathSync(DIST);stat=fs.statSync(real);}catch{return null;}
  if(!within(realDirectory,realDist)||!within(real,realDirectory)||!stat.isFile()||stat.size>IMAGE_LIMIT||!stat.size)return null;
  const data=fs.readFileSync(real);
  const valid=type==='png'?data.subarray(0,8).equals(Buffer.from([137,80,78,71,13,10,26,10])):type==='jpeg'?data[0]===255&&data[1]===216&&data[2]===255:data.toString('ascii',0,4)==='RIFF'&&data.toString('ascii',8,12)==='WEBP';
  if(!valid)return null;
  return {url:`data:image/${type};base64,${data.toString('base64')}`,bytes:data.length};
}
function loaderSource(mapping){
  return `/* Generated by scripts/build_question_ai_images.cjs. Images load only when requested. */
(()=>{
  'use strict';
  const mapping=Object.freeze(${JSON.stringify(mapping)});
  const scriptURL=document.currentScript?.src;
  const cache=new Map(),pending=new Map(),registered=new Set();
  const chunkURL=id=>new URL('question-image-data/chunk-'+String(id).padStart(4,'0')+'.js',scriptURL).href;
  const expected=new Map();
  for(const [src,id]of Object.entries(mapping)){if(!expected.has(id))expected.set(id,[]);expected.get(id).push(src);}
  function register(id,entries){
    if(!pending.has(id)||document.currentScript?.src!==chunkURL(id)||!Array.isArray(entries)||entries.length!==expected.get(id)?.length)return;
    const accepted=new Map();
    for(const entry of entries){
      if(!Array.isArray(entry)||entry.length!==2)return;
      const [src,url]=entry;
      if(!Object.hasOwn(mapping,src)||mapping[src]!==id||accepted.has(src)||typeof url!=='string'||url.length>2400100||!/^data:image\\/(?:png|jpeg|webp);base64,[A-Za-z0-9+/]+={0,2}$/.test(url))return;
      const data=url.slice(url.indexOf(',')+1);if(data.length%4!==0)return;
      accepted.set(src,url);
    }
    for(const [src,url]of accepted)cache.set(src,url);
    registered.add(id);
  }
  async function load(src){
    if(typeof src!=='string'||!Object.hasOwn(mapping,src)||!scriptURL)return null;
    if(cache.has(src))return {url:cache.get(src)};
    const id=mapping[src];
    if(!pending.has(id)){
      let resolveTask;
      const task=new Promise(resolve=>{resolveTask=resolve;});pending.set(id,task);
      const script=document.createElement('script');let timer,done=false;
      const finish=()=>{if(done)return;done=true;clearTimeout(timer);script.onload=null;script.onerror=null;script.remove();pending.delete(id);resolveTask(registered.has(id));};
      script.async=true;script.src=chunkURL(id);script.onload=finish;script.onerror=finish;
      timer=setTimeout(finish,10000);
      try{document.head.appendChild(script);}catch{finish();}
    }
    const task=pending.get(id);if(task)await task;
    return cache.has(src)?{url:cache.get(src)}:null;
  }
  window.GREQuestionImages=Object.freeze({load,register});
})();
`;
}
function build(){
  const bank=JSON.parse(fs.readFileSync(path.join(ROOT,'gre_question_bank.json'),'utf8')),mapping={},chunks=[],skipped=[];
  let rawBytes=0,entries=[];
  for(const src of eligibleAssets(bank)){
    const data=imageData(src);if(!data){skipped.push(src);continue;}
    const id=Math.floor(Object.keys(mapping).length/CHUNK_SIZE)+1;mapping[src]=id;rawBytes+=data.bytes;entries.push([src,data.url]);
    if(entries.length===CHUNK_SIZE){chunks.push(entries);entries=[];}
  }
  if(entries.length)chunks.push(entries);
  const sources=chunks.map((chunk,index)=>`/* Generated question image data; no API credentials. */\nwindow.GREQuestionImages?.register(${index+1},${JSON.stringify(chunk)});\n`),loader=loaderSource(mapping);
  const outputBytes=Buffer.byteLength(loader)+sources.reduce((total,source)=>total+Buffer.byteLength(source),0);
  if(outputBytes>OUTPUT_LIMIT)throw Error(`Image package would exceed 80 MiB (${outputBytes} bytes); no files written.`);
  fs.mkdirSync(OUTPUT,{recursive:true});
  sources.forEach((source,index)=>fs.writeFileSync(path.join(OUTPUT,`chunk-${String(index+1).padStart(4,'0')}.js`),source,'utf8'));
  fs.writeFileSync(LOADER,loader,'utf8');
  console.log(JSON.stringify({images:Object.keys(mapping).length,chunks:chunks.length,rawBytes,outputBytes,skipped},null,2));
}
if(require.main===module)build();
module.exports={eligibleAssets,imageData,loaderSource,build};
